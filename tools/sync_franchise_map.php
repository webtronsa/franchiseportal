<?php
// Builds the portal's franchise map (email => Base44 franchise id, name, admin) from the schools CRM configs,
// so the stats view uses the same email list the CRM signs in with. Run as root, for example daily from cron:
//   php sync_franchise_map.php /home/monkedotonlne/mnx-secrets/franchise_map.php monkedotonlne \
//       /home/monkeynet/public_html/api/config.php [/path/to/schools-copy/api/config.php ...]
// Each config is read by its own owner (not root) in a separate process. Later configs fill gaps, never override.
declare(strict_types=1);

if (PHP_SAPI !== 'cli') exit(1);
if ($argc < 4) { fwrite(STDERR, "usage: php sync_franchise_map.php OUT_FILE OUT_OWNER CONFIG [CONFIG ...]\n"); exit(2); }
[, $out, $owner] = $argv;
$configs = array_slice($argv, 3);

$map = [];
foreach ($configs as $config) {
    if (!is_file($config)) { fwrite(STDERR, "missing: $config\n"); exit(1); }
    $user = posix_getpwuid(fileowner($config))['name'] ?? '';
    $read = 'error_reporting(0); include $argv[1]; echo json_encode(defined("FRANCHISES") ? FRANCHISES : null);';
    $cmd = 'runuser -u ' . escapeshellarg($user) . ' -- php -r ' . escapeshellarg($read) . ' ' . escapeshellarg($config);
    $list = json_decode((string) shell_exec($cmd), true);
    if (!is_array($list)) { fwrite(STDERR, "no FRANCHISES list in $config\n"); exit(1); }
    foreach ($list as $email => $f) {
        $email = strtolower(trim((string) $email));
        if ($email === '' || isset($map[$email]) || !is_array($f)) continue;
        $map[$email] = ['id' => $f[0] ?? null, 'name' => (string) ($f[1] ?? ''), 'admin' => !empty($f[5])];
    }
}

// Written to a temp file and renamed, so the portal never reads a half-written map.
$tmp = $out . '.tmp';
file_put_contents($tmp, "<?php\n// Generated by sync_franchise_map.php on " . date(DATE_ATOM) . ". Do not edit.\nreturn " . var_export($map, true) . ";\n");
chown($tmp, $owner);
chgrp($tmp, $owner);
chmod($tmp, 0640);
rename($tmp, $out);
echo count($map) . " emails mapped\n";
