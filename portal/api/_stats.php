// Data sources for the stats view: the franchise map, Minastix (Base44) enrollments and the schools CRM databases.
// Everything here is read-only. The franchise is always decided by the signed-in email, never by the request.
declare(strict_types=1);

require_once __DIR__ . '/_common.php';

// Created on the server; returns:
// ['b44_api_key' => '..', 'b44_base' => 'https://minastix.base44.app/api/entities',
//  'franchise_map' => '/home/monkedotonlne/mnx-secrets/franchise_map.php',
//  'crm' => [['label' => 'monkeynastix.net', 'dsn' => 'mysql:host=localhost;dbname=..;charset=utf8mb4', 'user' => '..', 'pass' => '..'], ...]]
const MNX_STATS_CONFIG = '/home/monkedotonlne/mnx-secrets/stats.php';
const MNX_MX_TTL = 900; // seconds a Minastix result is reused before asking Base44 again

function mnx_stats_config(): array {
    static $cfg = null;
    if ($cfg === null) {
        if (!is_readable(MNX_STATS_CONFIG)) mnx_json(500, ['error' => 'stats unavailable']);
        $cfg = require MNX_STATS_CONFIG;
    }
    return $cfg;
}

// email => ['id' => Base44 franchise id or null, 'name' => .., 'admin' => bool], generated by tools/sync_franchise_map.php.
function mnx_franchise_map(): array {
    $path = mnx_stats_config()['franchise_map'] ?? '';
    $map = (is_string($path) && is_readable($path)) ? require $path : [];
    return is_array($map) ? $map : [];
}

function mnx_valid_fid(?string $fid): bool {
    return is_string($fid) && preg_match('/^[a-f0-9]{16,40}$/i', $fid) === 1;
}

// ── Minastix ──────────────────────────────────────────────────────────

// All enrollment records for one franchise, or every franchise when $fid is null. Null when Base44 cannot be read.
function mnx_mx_enrollments(?string $fid): ?array {
    $cfg = mnx_stats_config();
    $key = (string) ($cfg['b44_api_key'] ?? '');
    $base = rtrim((string) ($cfg['b44_base'] ?? 'https://minastix.base44.app/api/entities'), '/');
    if ($key === '') return null;

    $all = [];
    for ($skip = 0; $skip < 50000; $skip += 500) {
        $query = ['skip' => $skip, 'limit' => 500];
        if ($fid !== null) $query['q'] = json_encode(['franchise_id' => $fid]);
        $ch = curl_init($base . '/Enrollment?' . http_build_query($query));
        curl_setopt_array($ch, [
            CURLOPT_RETURNTRANSFER => true,
            CURLOPT_HTTPHEADER => ['api_key: ' . $key, 'Accept: application/json'],
            CURLOPT_TIMEOUT => 25,
        ]);
        $raw = curl_exec($ch);
        $code = (int) curl_getinfo($ch, CURLINFO_RESPONSE_CODE);
        curl_close($ch);
        if ($code !== 200 || !is_string($raw)) return $skip === 0 ? null : $all;
        $data = json_decode($raw, true);
        if (!is_array($data)) return $skip === 0 ? null : $all;
        $batch = $data['entities'] ?? (array_is_list($data) ? $data : []);
        if (!is_array($batch) || !$batch) break;
        array_push($all, ...$batch);
        if (count($batch) < 500) break;
    }
    return $all;
}

function mnx_month_keys(int $back, int $ahead = 0): array {
    $keys = [];
    $start = new DateTimeImmutable('first day of this month', new DateTimeZone('Africa/Johannesburg'));
    for ($i = -$back + 1; $i <= $ahead; $i++) $keys[] = $start->modify("$i month")->format('Y-m');
    return $keys;
}

// Venue names in Minastix carry the programme as a suffix ("Sunnyside Monkeynastix"); the school is the rest.
function mnx_school_name(string $venue): string {
    return trim((string) preg_replace('/\s+(monkeynastix|babynastix|supernastix|bnx|mnx)$/i', '', trim($venue)));
}

function mnx_top(array $counts, int $n): array {
    arsort($counts);
    $out = [];
    $other = 0;
    foreach ($counts as $label => $count) {
        if (count($out) < $n) $out[] = ['label' => (string) $label, 'value' => $count];
        else $other += $count;
    }
    if ($other > 0) $out[] = ['label' => 'Other', 'value' => $other];
    return $out;
}

function mnx_mx_summary(array $rows, array $names): array {
    $byStatus = $byVenue = $byProgram = $byFranchise = [];
    $months = array_fill_keys(mnx_month_keys(12), 0);
    $confirmed = 0;
    foreach ($rows as $e) {
        $status = strtolower(trim((string) ($e['enrollment_status'] ?? 'unknown'))) ?: 'unknown';
        $byStatus[$status] = ($byStatus[$status] ?? 0) + 1;
        if ($status !== 'confirmed') continue;
        $confirmed++;
        $venue = mnx_school_name((string) ($e['venue_name'] ?? ''));
        if ($venue !== '') $byVenue[$venue] = ($byVenue[$venue] ?? 0) + 1;
        $prog = ucfirst(strtolower(trim((string) ($e['program_id'] ?? '')))) ?: 'Unspecified';
        $byProgram[$prog] = ($byProgram[$prog] ?? 0) + 1;
        $month = substr((string) ($e['created_date'] ?? ''), 0, 7);
        if (isset($months[$month])) $months[$month]++;
        $f = (string) ($e['franchise_id'] ?? '');
        $fname = $names[$f] ?? trim((string) ($e['franchise_name'] ?? '')) ?: 'Unknown';
        $byFranchise[$fname] = ($byFranchise[$fname] ?? 0) + 1;
    }
    $monthly = [];
    foreach ($months as $m => $v) $monthly[] = ['label' => $m, 'value' => $v];
    return [
        'confirmed' => $confirmed,
        'venues' => count($byVenue),
        'by_status' => array_map(fn($r) => ['label' => ucfirst($r['label'])] + $r, mnx_top($byStatus, 8)),
        'by_venue' => mnx_top($byVenue, 8),
        'by_program' => mnx_top($byProgram, 6),
        'by_month' => $monthly,
        'by_franchise' => mnx_top($byFranchise, 10),
    ];
}

// The enrollment summary for a franchise (or all), reused for MNX_MX_TTL seconds from the portal database.
// When Base44 is down, the last good copy is returned and marked stale.
function mnx_mx_stats(?string $fid, array $names): array {
    $cacheKey = 'mx:' . ($fid ?? 'all');
    $pdo = null;
    $cached = null;
    try {
        if (is_readable(MNX_DB_CONFIG)) $pdo = mnx_db();
    } catch (Throwable $e) {
        error_log('portal stats: cache unavailable: ' . $e->getMessage()); // still serve live numbers
    }
    if ($pdo) {
        $pdo->exec('CREATE TABLE IF NOT EXISTS stats_cache (cache_key VARCHAR(80) NOT NULL PRIMARY KEY, data MEDIUMTEXT NOT NULL, fetched_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP) DEFAULT CHARSET = utf8mb4');
        $stmt = $pdo->prepare('SELECT data, UNIX_TIMESTAMP(fetched_at) AS ts FROM stats_cache WHERE cache_key = ?');
        $stmt->execute([$cacheKey]);
        $cached = $stmt->fetch() ?: null;
        if ($cached && time() - (int) $cached['ts'] < MNX_MX_TTL) {
            return json_decode($cached['data'], true) + ['available' => true, 'fetched_at' => date(DATE_ATOM, (int) $cached['ts'])];
        }
    }
    $rows = mnx_mx_enrollments($fid);
    if ($rows === null) {
        if ($cached) return json_decode($cached['data'], true) + ['available' => true, 'stale' => true, 'fetched_at' => date(DATE_ATOM, (int) $cached['ts'])];
        return ['available' => false];
    }
    $summary = mnx_mx_summary($rows, $names);
    if ($pdo) {
        $pdo->prepare('INSERT INTO stats_cache (cache_key, data) VALUES (?, ?) ON DUPLICATE KEY UPDATE data = VALUES(data), fetched_at = CURRENT_TIMESTAMP')
            ->execute([$cacheKey, json_encode($summary)]);
    }
    return $summary + ['available' => true, 'fetched_at' => date(DATE_ATOM)];
}

// ── Schools CRM ───────────────────────────────────────────────────────

// Reads every configured CRM database (monkeynastix.net and the schools copy) and merges them,
// so a school or visit that exists in both is counted once.
function mnx_crm_stats(?string $fid): array {
    $sources = mnx_stats_config()['crm'] ?? [];
    $schools = $visits = [];
    $read = 0;
    $where = $fid === null ? '' : ' WHERE franchise_id = ?';
    $args = $fid === null ? [] : [$fid];
    foreach ($sources as $src) {
        try {
            $pdo = new PDO($src['dsn'], $src['user'], $src['pass'], [
                PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
                PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
                PDO::ATTR_TIMEOUT => 5,
            ]);
            $stmt = $pdo->prepare('SELECT franchise_id, emis, status, followup_date, updated_at FROM school_engagement' . $where);
            $stmt->execute($args);
            foreach ($stmt as $r) {
                $k = $r['franchise_id'] . '|' . $r['emis'];
                if (!isset($schools[$k]) || $r['updated_at'] > $schools[$k]['updated_at']) $schools[$k] = $r;
            }
            $stmt = $pdo->prepare('SELECT franchise_id, emis, visit_date, visit_type, done FROM visits'
                . ($where ? $where . ' AND' : ' WHERE') . ' visit_date >= DATE_SUB(CURDATE(), INTERVAL 6 MONTH)');
            $stmt->execute($args);
            foreach ($stmt as $r) {
                $k = $r['franchise_id'] . '|' . $r['emis'] . '|' . $r['visit_date'] . '|' . $r['visit_type'];
                $visits[$k] = isset($visits[$k]) ? ['done' => max((int) $visits[$k]['done'], (int) $r['done'])] + $r : $r;
            }
            $read++;
        } catch (Throwable $e) {
            error_log('portal stats: CRM source ' . ($src['label'] ?? '?') . ' failed: ' . $e->getMessage());
        }
    }
    if ($read === 0) return ['available' => false];

    $today = (new DateTimeImmutable('today', new DateTimeZone('Africa/Johannesburg')))->format('Y-m-d');
    $in30 = (new DateTimeImmutable('+30 days', new DateTimeZone('Africa/Johannesburg')))->format('Y-m-d');
    $stages = array_fill_keys(['prospect', 'contacted', 'hot', 'active', 'inactive'], 0);
    $overdue = 0;
    foreach ($schools as $s) {
        if (isset($stages[$s['status']])) $stages[$s['status']]++;
        if ($s['followup_date'] && $s['followup_date'] < $today && !in_array($s['status'], ['active', 'inactive'], true)) $overdue++;
    }
    $months = array_fill_keys(mnx_month_keys(6), 0);
    $upcoming = $done = 0;
    foreach ($visits as $v) {
        $m = substr((string) $v['visit_date'], 0, 7);
        if ((int) $v['done'] === 1) { $done++; if (isset($months[$m])) $months[$m]++; }
        elseif ($v['visit_date'] >= $today && $v['visit_date'] <= $in30) $upcoming++;
    }
    $pipeline = [];
    foreach ($stages as $stage => $n) $pipeline[] = ['label' => ucfirst($stage), 'value' => $n];
    $monthly = [];
    foreach ($months as $m => $n) $monthly[] = ['label' => $m, 'value' => $n];

    return [
        'available' => true,
        'schools' => count($schools),
        'active' => $stages['active'],
        'pipeline' => $pipeline,
        'overdue_followups' => $overdue,
        'visits_upcoming_30d' => $upcoming,
        'visits_done_6m' => $done,
        'visits_by_month' => $monthly,
        'partial' => $read < count($sources),
    ];
}
